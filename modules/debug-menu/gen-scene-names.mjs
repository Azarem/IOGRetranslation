#!/usr/bin/env node
//
// gen-scene-names.mjs — Regenerate scene name strings for debug_menu_tables.asm.
//
// Reads groups.json and generates:
//   - Header strings with "-" prefix: |-GroupName|
//   - Scene strings with indent and group prefix stripped: |  SubName|
//
// The group name is derived from the group key (title case).
// If a scene description starts with "GroupName - ", that prefix is stripped.
// Scene names are truncated to fit the BG3 display width (~24 chars).
//
// Usage:  node gen-scene-names.mjs
// Output: stdout (paste into debug_menu_tables.asm)

import { readFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const groupsPath = resolve(__dirname, '../../../../gaia-iog-baserom/db-us/groups.json');
const groups = JSON.parse(readFileSync(groupsPath, 'utf8'));

const MAX_NAME_LEN = 24; // max chars per scene name string (incl. indent)

function titleCase(key) {
  return key.replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
}

// Some groups have abbreviations or name variations in their scene descriptions.
// Map group key → actual prefix used in scene descriptions.
const prefixOverrides = {
  mountain_temple: 'Mt. Temple',
  seaside_palace: 'Seabed Palace',
};

function getStripPrefix(groupKey) {
  return prefixOverrides[groupKey] || titleCase(groupKey);
}

function stripGroupPrefix(description, groupKey) {
  const prefix = getStripPrefix(groupKey);
  if (description.startsWith(prefix + ' - ')) {
    return description.slice(prefix.length + 3);
  }
  return description;
}

const lines = [];
lines.push('---------------------------------------------');
lines.push('; Scene name strings — generated by gen-scene-names.mjs.');
lines.push('; Headers prefixed with "-", scenes indented with 2 spaces.');
lines.push('; Group name stripped from scene descriptions where redundant.');
lines.push(`; Max ${MAX_NAME_LEN} chars per entry for BG3 display width.`);
lines.push('');

let idx = 0;
for (const [groupKey, group] of Object.entries(groups)) {
  const groupName = titleCase(groupKey);

  // Header entry
  const hdrHex = idx.toString(16).padStart(3, '0');
  const hdrStr = `-${groupName}`;
  lines.push(`sn_${hdrHex} |${hdrStr.slice(0, MAX_NAME_LEN)}|`);
  idx++;

  // Scene entries
  if (group.scenes) {
    for (const [sceneKey, scene] of Object.entries(group.scenes)) {
      const hex = idx.toString(16).padStart(3, '0');
      const stripped = stripGroupPrefix(scene.description, groupKey);
      const display = `  ${stripped}`;
      lines.push(`sn_${hex} |${display.slice(0, MAX_NAME_LEN)}|`);
      idx++;
    }
  }
}

console.error(`Generated ${idx} scene name strings`);
process.stdout.write(lines.join('\n') + '\n');
